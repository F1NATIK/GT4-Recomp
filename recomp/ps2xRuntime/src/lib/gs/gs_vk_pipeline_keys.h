// GT4's Vulkan pipelines, built in (vkgl's pipeline store, gs_vkgl.cpp): the
// renderer's GS draw pipelines a run makes over boot, the menus, the car
// select and races. When the renderer links a program, the ones listed for it
// are built on the store's threads before the first draw needs them, also on
// a first run (no key file yet). Each is the program by its OpenGL source
// (exact) and by its variant (its #version / #extension / #define lines and
// uniform names: still the same after an edit of a shader's body), and the
// state (VkFormat numbers, OpenGL blend enums). An entry that matches no
// program costs nothing; one that matches a program it was not made for costs
// one background compile, never a picture.
//
// Generated by analysis/vulkan/scripts/gen_pipeline_keys.py from the key
// files (vk-pipelines-keys.txt) of headless runs; see analysis/vulkan.
// Last 15 (2026-10-16, GPU Z16 buffers and full-colour display buffer reads
// in GT4's 480p menus, analysis/design/menus-480p/scripts/regen-vk-keys.ps1):
// the list as it was first (its order kept), then cold-cache Vulkan runs at
// 3x over the 480p car and colour select (z16-k1: GT4's own Z16 for the car
// passes, drawn in fast mode, and its per-batch specialised programs) and
// the same route in 480i (z16-k480i). The draw program's #define lines are
// unchanged (the Z16 clamp and the full-colour read use existing state
// words), so the entries before still match it by variant. Without these the
// first 480p car select made 13 pipelines on the spot (15 s of waiting on a
// cold driver cache).
// Before (2026-10-08, the Full launcher's internal resolution,
// analysis/design/full-m2/scripts/regen-vk-keys.ps1): the list as it was
// first (its order kept), then the pipelines GT4 needs at 3x and 4x, where
// GT4.exe draws in fast mode (its rasterizing program and per-batch
// specialised programs, blending on the GPU's blend unit): cold-cache Vulkan
// runs of the full-m2 tree over boot, the menus, the car select and a 480p
// race at each scale, a 4x New York race (its own specialised programs),
// the 16-bit race colour, the night course at 4x and the Nordschleife's
// B-Spec Race Monitor at 3x. At 2x (exact) GT4 needs no state the list
// lacked.
// Without them a first 4x race made 49 pipelines on the spot (18.6 s of
// waiting in all, the fast program's about 2 s each).
// First 17 (2026-10-08, Test Build 4 integration, analysis/integration/tb4/
// scripts/vk-keys.ps1): the integrated main tree's (picture review, sound,
// 480p-colour with its review fixes, full launcher), from two hidden Vulkan
// runs with the Full launcher's default settings: boot, the menus, the car
// select and a 480p New York race (tb4-vkkeys-ny1, 17 states), and two 480p
// sessions with GT4's 480i menus between them (tb4-vkkeys-2s, the same 16 of
// them). The 480p-colour review fixes and the picture review gave all four
// programs these runs use new sources; their 17 states were all in the list
// below (15 of them in the 480p-colour tree's 15), where they matched only by
// variant.
// Next 15 (2026-10-08, analysis/design/480p-colour/scripts/regen-vk-keys.ps1):
// the 480p-colour tree's, from a cold-cache Vulkan run over boot, the menus,
// the car select and a 480p race (run p2-vkcmp). Since the list below was
// made, GS dithering and the picture track's present modes (c61eb19) and the
// race colour (a CT16 target's texels read as their 16-bit value) changed
// the GS draw, interlock and field / present programs: all three have new
// sources. The 22 after them are the list as it was (the
// integrated tree's 17 states first): they also serve the new sources' other
// states by their variant.
// Before that, three shader trees, the same 17 states: the integrated tree's (first 17,
// 2026-10-07: the video modes' field / present program has new uniforms, so
// a new hash for its one state; the other 16 are step 6's), phase 5 step 6's
