"""make_late_functions.py - GT4's pointer-only functions that the main recompiled set lacks, as one source file.

GT4's LAN path calls functions that Ghidra's function list missed (reached only through function pointers, e.g. RTIME's
0x523160 from 0x52d044): the dispatcher logs "[guest-branch:missing-target]" and skips the call, and the network page
then waits for ever ("Connecting..."). ps2_recomp makes them when their addresses are given as extra entry points; a run
with every gap between Ghidra's functions added (gaps.py) gives 785 new functions and leaves every existing generated
file byte-identical (only ps2_recompiled_functions.h and register_functions.cpp gain lines).

Rather than regenerating analysis\\core-generated (a full rebuild of 27k functions, the build kit's snapshot and the
Classic build), this script puts the new functions into one file compiled into GT4.exe, with a function that enters
them in the dispatch table (only slots that are still empty) - installed by the runtime when GT4_NET is on.

usage: python make_late_functions.py <old core-generated> <new ps2_recomp output> <out .cpp>
"""
import os
import re
import sys


def main():
    old, new, out = sys.argv[1:4]
    names = sorted(set(os.listdir(new)) - set(os.listdir(old)))
    funcs = []
    bodies = []
    for f in names:
        if not f.endswith('.cpp'):
            continue
        text = open(os.path.join(new, f), encoding='utf-8').read().replace('\r\n', '\n')
        m = re.search(r'^void (\w+)\(uint8_t\* rdram, R5900Context\* ctx, PS2Runtime \*runtime\) \{', text, re.M)
        if not m:
            raise SystemExit('no function in ' + f)
        funcs.append(m.group(1))
        start = text.rfind('// Function:', 0, m.start())
        bodies.append(text[start if start >= 0 else m.start():].rstrip() + '\n')
    table = []
    oldreg = open(os.path.join(old, 'register_functions.cpp'), encoding='utf-8').read().replace('\r\n', '\n').splitlines()
    newreg = open(os.path.join(new, 'register_functions.cpp'), encoding='utf-8').read().replace('\r\n', '\n').splitlines()
    oldset = set(oldreg)
    known = set(funcs)
    for line in newreg:
        if line in oldset:
            continue
        m = re.match(r'\s*g_ps2RecompiledFunctionTable\[\d+\] = (\w+); // (0x[0-9a-f]+)', line)
        if not m:
            raise SystemExit('unexpected new line in register_functions.cpp: ' + line)
        if m.group(1) not in known:
            raise SystemExit('a new table line names an old function: ' + line)
        table.append((int(m.group(2), 16), m.group(1)))
    o = []
    o.append('// GENERATED by analysis/design/multi-monitor/scripts/make_late_functions.py from ps2_recomp output (do not edit).')
    o.append('// GT4 CORE functions reached only through pointers that the main generated set lacks (%d functions, %d table'
             % (len(funcs), len(table)))
    o.append('// entries). Entered in the dispatch table by gt4InstallLateFunctions (empty slots only) when GT4_NET is on.')
    o.append('#include <cstdint>')
    o.append('#include <cstdio>')
    o.append('#include <stdexcept>')
    o.append('#include "ps2_runtime_macros.h"')
    o.append('#include "ps2_runtime.h"')
    o.append('#include "ps2_recompiled_functions.h"')
    o.append('#include "ps2_recompiled_stubs.h"')
    o.append('#include "ps2_syscalls.h"')
    o.append('#include "ps2_stubs.h"')
    o.append('#ifdef PS2_FUNCTION_LOG_TRACKER')
    o.append('#include "ps2_log.h"')
    o.append('#endif')
    o.append('')
    for f in funcs:
        o.append('void %s(uint8_t* rdram, R5900Context* ctx, PS2Runtime *runtime);' % f)
    o.append('')
    o.extend(bodies)
    o.append('namespace')
    o.append('{')
    o.append('    struct LateEntry')
    o.append('    {')
    o.append('        uint32_t address;')
    o.append('        PS2Runtime::RecompiledFunction function;')
    o.append('    };')
    o.append('    const LateEntry kLateEntries[] = {')
    for a, f in table:
        o.append('        {0x%xu, %s},' % (a, f))
    o.append('    };')
    o.append('}')
    o.append('')
    o.append('// Enters the functions in empty dispatch-table slots; returns how many were entered.')
    o.append('int gt4InstallLateFunctions(PS2Runtime &runtime)')
    o.append('{')
    o.append('    int entered = 0;')
    o.append('    for (const LateEntry &e : kLateEntries)')
    o.append('        if (!runtime.hasFunction(e.address) && runtime.replaceFunction(e.address, e.function))')
    o.append('            ++entered;')
    o.append('    return entered;')
    o.append('}')
    o.append('')
    o.append('// The runtime (Gt4HostGlue.cpp) calls it through this pointer: the generated code lives in GT4.exe, not in the')
    o.append('// ps2_runtime library.')
    o.append('extern int (*g_gt4LateFunctionsInstaller)(PS2Runtime &);')
    o.append('namespace')
    o.append('{')
    o.append('    const bool kLateInstallerSet = (g_gt4LateFunctionsInstaller = &gt4InstallLateFunctions, true);')
    o.append('}')
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('\n'.join(o) + '\n')
    print('%s: %d functions, %d table entries, %d bytes' % (out, len(funcs), len(table), os.path.getsize(out)))


if __name__ == '__main__':
    main()
